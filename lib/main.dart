// Generated by `flutterfire configure` (see README). Not included in source.
import 'firebase_options.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  SystemChrome.setSystemUIOverlayStyle(SystemUiOverlayStyle.light);
  await SystemChrome.setPreferredOrientations([DeviceOrientation.portraitUp]);

  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await configureDependencies();

  // Before the session starts, so a tap that launched the app is kept until
  // the customer is signed in.
  await sl<LocalNotificationService>().init(onOpen: _openNotification);

  final session = sl<SessionCubit>();
  // Subscribed before start() so no session change is missed.
  session.stream.listen(_bindCustomerData);

  // Start listening to FirebaseAuth.authStateChanges() and the user profile.
  session.start();

  runApp(const App());
}

/// The cart, favorites and notifications follow the signed-in customer.
/// Admins have none of them, and signing out clears them.
void _bindCustomerData(SessionState session) {
  final uid =
      session.status == SessionStatus.customer ? session.user?.uid : null;
  sl<CartCubit>().bindUser(uid);
  sl<FavoritesCubit>().bindUser(uid);
  sl<NotificationsCubit>().bindUser(uid);
  sl<LocalNotificationService>().bindUser(uid);
}

/// A tapped notification opens its order (with Home and My orders behind
/// it) and counts as read.
void _openNotification(NotificationTap tap) {
  sl<NotificationsCubit>().markRead(tap.notificationId);
  final orderId = tap.orderId;
  // Next event loop: lets the router finish reacting to the session first.
  Future(() {
    final router = sl<GoRouter>();
    if (orderId == null) {
      router.goNamed(RouteNames.notifications);
    } else {
      router.goNamed(RouteNames.orderDetails, pathParameters: {'id': orderId});
    }
  });
}
